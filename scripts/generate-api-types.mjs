#!/usr/bin/env node
/**
 * Generate app/frontend/src/types/generated/backend.ts from the backend's
 * OpenAPI schema.
 *
 * By default the schema comes from the backend code itself:
 * scripts/export_openapi.py writes `create_app().openapi()` to a temporary
 * file (no server, no lifespan), and openapi-typescript reads that file. Pass a
 * path or URL (argument or OPENAPI_SPEC) to generate from another schema, for
 * example a running server's /openapi.json. There is no fallback: if the
 * schema cannot be loaded the script fails instead of generating stale types.
 *
 * Options:
 *   --out <file>   Write somewhere other than backend.ts (used by ci:check's
 *                  drift step to compare against the committed file).
 * Environment:
 *   OPENAPI_SPEC   Schema path or URL; overrides the exported schema.
 *   PYTHON         Python interpreter for the export (default: python, then python3).
 */
import { spawnSync } from 'node:child_process';
import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath, pathToFileURL } from 'node:url';

import openapiTS, { astToString } from 'openapi-typescript';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const EXPORT_SCRIPT = path.join(REPO_ROOT, 'scripts', 'export_openapi.py');
const DEFAULT_OUTPUT_FILE = path.join(REPO_ROOT, 'app/frontend/src/types/generated/backend.ts');

const HEADER_COMMENT = `/**
 * This file is auto-generated by scripts/generate-api-types.mjs from the
 * backend's OpenAPI schema. Do not edit it directly; run
 * \`npm run generate:api-types\` instead.
 */`;

function parseArgs(argv) {
  const parsed = { source: undefined, out: DEFAULT_OUTPUT_FILE };
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === '--out') {
      const value = argv[index + 1];
      if (!value) {
        throw new Error('--out needs a file path');
      }
      parsed.out = path.resolve(value);
      index += 1;
    } else if (arg.startsWith('--out=')) {
      parsed.out = path.resolve(arg.slice('--out='.length));
    } else if (!parsed.source) {
      parsed.source = arg;
    } else {
      throw new Error(`Unexpected argument: ${arg}`);
    }
  }
  return parsed;
}

function toOpenAPIInput(value) {
  if (/^https?:\/\//i.test(value)) {
    return value;
  }
  return pathToFileURL(path.resolve(value)).href;
}

function exportBackendSpec(destination) {
  const candidates = process.env.PYTHON ? [process.env.PYTHON] : ['python', 'python3'];
  for (const python of candidates) {
    const result = spawnSync(python, [EXPORT_SCRIPT, destination], {
      cwd: REPO_ROOT,
      stdio: ['ignore', 'inherit', 'inherit'],
    });
    if (result.error?.code === 'ENOENT') {
      continue;
    }
    if (result.error) {
      throw result.error;
    }
    if (result.status !== 0) {
      throw new Error(
        `${python} scripts/export_openapi.py exited with status ${result.status}. ` +
          'Install the backend dependencies (pip install -r requirements.txt) and retry.',
      );
    }
    return;
  }
  throw new Error(
    `No Python interpreter found (tried ${candidates.join(', ')}). Set PYTHON to one ` +
      'with the backend dependencies installed.',
  );
}

async function generate(source) {
  console.log(`[generate-api-types] Generating types from ${source}`);
  const ast = await openapiTS(toOpenAPIInput(source));
  return `${HEADER_COMMENT}\n\n${astToString(ast)}\n`;
}

let tempDir;
try {
  const { source: argSource, out } = parseArgs(process.argv.slice(2));
  let source = process.env.OPENAPI_SPEC ?? argSource;

  if (!source) {
    tempDir = await mkdtemp(path.join(os.tmpdir(), 'lora-openapi-'));
    source = path.join(tempDir, 'openapi.json');
    console.log('[generate-api-types] Exporting the OpenAPI schema from backend.main.create_app()');
    exportBackendSpec(source);
  }

  const output = await generate(source);
  await mkdir(path.dirname(out), { recursive: true });
  await writeFile(out, output, 'utf8');
  const shown = path.relative(process.cwd(), out);
  console.log(`[generate-api-types] Wrote ${shown.startsWith('..') ? out : shown}`);
} catch (error) {
  console.error('[generate-api-types] Failed to generate API types.');
  console.error(error instanceof Error ? error.message : error);
  process.exitCode = 1;
} finally {
  if (tempDir) {
    await rm(tempDir, { recursive: true, force: true });
  }
}
